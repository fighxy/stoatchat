// =============================================================================
// ФАЙЛ: crates/bonfire/src/main.rs
// НАЗНАЧЕНИЕ: Точка входа WebSocket-сервера (bonfire) — порт 14703.
//   Bonfire отвечает за доставку событий реального времени (новые сообщения,
//   изменения каналов, присутствие пользователей) через протокол WebSocket.
//
// КЛЮЧЕВЫЕ КОНЦЕПТЫ:
// - #[async_std::main] — async-точка входа с async_std runtime
// - TcpListener — низкоуровневый TCP-сервер
// - async_std::task::spawn — конкурентная обработка множества соединений
// - env::var — чтение переменных окружения для конфигурации
// =============================================================================

// `use std::env` — стандартная библиотека для работы с переменными окружения.
// Позволяет читать переменные через `env::var("KEY")`.
use std::env;

// `TcpListener` из async_std — асинхронный TCP-слушатель.
// В отличие от стандартного `std::net::TcpListener`, не блокирует поток при ожидании.
use async_std::net::TcpListener;

// `clear_region` — очищает информацию о присутствии пользователей (online/offline)
// при старте сервера. Это нужно потому что при перезапуске все WebSocket-соединения
// обрываются, и старые записи о присутствии становятся неактуальными.
use revolt_presence::clear_region;

// `#[macro_use] extern crate log` — подключаем макросы логирования (info!, warn!, error!).
// Конкретный вывод (stderr, файл, systemd) настраивается через revolt_config.
#[macro_use]
extern crate log;

// `pub mod config` — конфигурация Bonfire (настройки WebSocket, таймауты).
// `pub` — публично, доступно для тестирования и других модулей.
pub mod config;
// `pub mod events` — обработка событий WebSocket-протокола (аутентификация, подписки).
pub mod events;

// `mod database` — подключение к БД (приватный модуль, инкапсулирован).
mod database;
// `mod websocket` — логика обработки WebSocket-соединений (основной код сервера).
mod websocket;

// =============================================================================
// ТОЧКА ВХОДА
// =============================================================================

// `#[async_std::main]` — атрибут-макрос, заменяющий стандартный `fn main()`.
// Он создаёт async_std runtime и запускает нашу async-функцию в нём.
// Почему async_std, а не tokio? Bonfire исторически использует async_std
// (async-tungstenite WebSocket библиотека изначально разрабатывалась для него).
#[async_std::main]
async fn main() {
    // Инициализируем конфигурацию и логирование для events-сервиса.
    // `configure!(events)` — макрос revolt_config: настраивает Sentry, логгер,
    // читает Revolt.toml. Параметр "events" определяет набор настроек.
    revolt_config::configure!(events);

    // Подключаемся к базе данных (инициализируем глобальное соединение).
    // `await` — ждём завершения async-операции (подключение к MongoDB/Redis).
    database::connect().await;

    // =============================================================================
    // ОЧИСТКА ДАННЫХ ПРИСУТСТВИЯ
    // =============================================================================

    // Читаем переменную окружения NO_CLEAR_PRESENCE.
    // `env::var("...")` возвращает `Result<String, VarError>`:
    //   - Ok(value) если переменная установлена
    //   - Err(...) если переменная отсутствует
    // `.unwrap_or_else(|_| "0".into())` — при отсутствии переменной используем "0".
    // `|_|` — замыкание, игнорирующее аргумент (ошибку), возвращает дефолтное значение.
    let no_clear_region = env::var("NO_CLEAR_PRESENCE").unwrap_or_else(|_| "0".into()) == "1";

    if !no_clear_region {
        // `clear_region(None)` — очищаем данные присутствия для текущего региона.
        // `None` означает "текущий регион" (из конфига).
        // При горячем перезапуске (rolling deploy) можно установить NO_CLEAR_PRESENCE=1,
        // чтобы не сбрасывать присутствие пока работает другой инстанс.
        clear_region(None).await;
    }

    // =============================================================================
    // TCP-СЕРВЕР
    // =============================================================================

    // Читаем адрес для привязки сервера из переменной окружения HOST.
    // `"0.0.0.0:14703"` — значение по умолчанию:
    //   - `0.0.0.0` — слушать на всех сетевых интерфейсах (нужно для Docker/production)
    //   - `14703` — порт WebSocket-сервера (bonfire)
    let bind = env::var("HOST").unwrap_or_else(|_| "0.0.0.0:14703".into());
    // `info!` — макрос логирования (уровень INFO). Форматирование как в println!,
    // но с добавлением timestamp, уровня и имени модуля.
    info!("Listening on host {bind}");

    // `TcpListener::bind(bind).await` — асинхронно привязываемся к адресу.
    // Создаёт сокет, связывает его с адресом и начинает слушать входящие соединения.
    let try_socket = TcpListener::bind(bind).await;

    // `.expect("...")` — паникует с сообщением если Result::Err.
    // Используем panic здесь потому что без сокета сервер не может работать вообще.
    let listener = try_socket.expect("Failed to bind");

    // =============================================================================
    // ЦИКЛ ПРИЁМА СОЕДИНЕНИЙ
    // =============================================================================

    // `while let Ok((stream, addr)) = listener.accept().await` — паттерн-матчинг в цикле.
    // `listener.accept()` — асинхронно ждёт следующего входящего TCP-соединения.
    // Возвращает `(TcpStream, SocketAddr)` — поток данных и адрес клиента.
    // Если Ok — разбираем на `stream` (данные) и `addr` (IP:порт клиента).
    // Если Err — цикл завершается (критическая ошибка сокета).
    while let Ok((stream, addr)) = listener.accept().await {
        // `async_std::task::spawn` — запускаем обработку соединения как отдельную задачу.
        // Это ключевой паттерн конкурентного сервера: каждое соединение обрабатывается
        // независимо, не блокируя принятие новых соединений.
        //
        // В отличие от thread::spawn, это НЕ создаёт новый поток ОС.
        // async_std runtime планирует задачи на пуле потоков (обычно N = количество CPU).
        // Сотни WebSocket-соединений обрабатываются в десятках потоков — эффективно!
        //
        // `async move { ... }` — async-замыкание, которое перемещает (`move`) захваченные
        // переменные внутрь (stream и addr переходят во владение замыкания).
        async_std::task::spawn(async move {
            info!("User connected from {addr:?}");

            // Передаём управление модулю websocket для обработки протокола.
            // `database::get_db()` — получает глобальный экземпляр Database.
            // Функция возвращается когда соединение закрывается (нормально или с ошибкой).
            websocket::client(database::get_db(), stream, addr).await;

            info!("User disconnected from {addr:?}");
        });
        // После spawn сразу возвращаемся к ожиданию следующего соединения.
        // Задача выполняется параллельно в runtime.
    }
}
