// `#[macro_use]` — атрибут, который импортирует ВСЕ макросы из указанного
// крейта в текущую область видимости, чтобы не писать полный путь при каждом вызове.
// `extern crate auto_ops` — подключает крейт auto_ops, который предоставляет
// макросы для автоматической реализации арифметических операторов
// (например, |=, &= для битовых полей прав доступа).
#[macro_use]
extern crate auto_ops;

// Подключаем крейт async_trait. Он нужен потому, что Rust нативно не поддерживает
// `async fn` внутри трейтов (на момент написания этого кода).
// Макрос `#[async_trait]` обходит это ограничение, превращая async-методы
// трейтов в возвращающие `Pin<Box<dyn Future>>`.
#[macro_use]
extern crate async_trait;

// `mod r#impl;` — объявляет модуль из файла src/impl.rs.
// Префикс `r#` (raw identifier) нужен потому, что `impl` — ключевое слово Rust.
// Без `r#` компилятор воспринял бы это как синтаксическую ошибку.
mod r#impl;

// Объявление внутреннего модуля `models` — данные (структуры и перечисления)
// для работы с правами доступа (права пользователя, сервера, канала).
mod models;

// Объявление внутреннего модуля `trait` (trait.rs).
// Здесь определены трейты, описывающие интерфейс для запроса прав доступа.
// Также требует `r#` по той же причине — `trait` является ключевым словом.
mod r#trait;

// `pub use models::*;` — реэкспорт ВСЕГО публичного содержимого модуля `models`
// как части публичного API этого крейта. Пользователи крейта смогут писать
// `use revolt_permissions::ChannelPermission` вместо полного пути.
pub use models::*;
pub use r#impl::*;
pub use r#trait::*;

// `#[cfg(test)]` — условная компиляция: этот блок включается ТОЛЬКО при запуске
// тестов (`cargo test`). В обычной сборке этот модуль полностью исключается,
// что экономит размер итогового бинарника.
#[cfg(test)]
mod test;
